/// Sections appear in the reference's order, so a diff of one does not churn
/// another.
#[test]
fn sections_appear_in_the_fixed_order() {
    let d = Design::new();
    let clk = d.input("clk", 1).unwrap();
    let data = d.input("data", 8).unwrap();
    let sum = d.add(&data, &data).unwrap();
    let held = d
        .reg(&sum, &clk, &d.constant(false), &d.constant(false))
        .unwrap();
    let wired = d.wire(8).unwrap();
    d.drive(&wired, &held).unwrap();
    d.output("q", 8, &wired).unwrap();
    let text = module(&d, &clk, "order").emit().unwrap();
    let ports = text.find("module order (").unwrap();
    let declaration = text.find("wire [7:0] signal_Add;").unwrap_or(usize::MAX);
    let statement = text.find("assign signal_Add").unwrap_or(usize::MAX);
    let alias = text.find("assign signal_Wire").unwrap_or(usize::MAX);
    let output = text.find("assign q").unwrap_or(usize::MAX);
    let end = text.find("endmodule").unwrap();
    assert!(ports < declaration, "{text}");
    assert!(declaration < statement, "{text}");
    assert!(statement < alias, "{text}");
    assert!(alias < output, "{text}");
    assert!(output < end, "{text}");
}

