//! Whole modules as text, and the properties the text is supposed to have.
//!
//! # Why goldens and not a simulator
//!
//! The design notes keep snapshot tests on emitted Verilog
//! ([`docs/design-notes.md`](https://github.com/ostrium-labs/ferrite-lithic/blob/dev/docs/design-notes.md)
//! §6) and *substitute* for Hardcaml's golden waveforms, because those are ASCII
//! renders from a proprietary external library. So: compare text.
//!
//! Each golden below is a design small enough to read in full and to check against
//! the IR by hand. When one of them changes, the change is either a decision worth
//! arguing about or a bug, and both are visible in the diff. `tests/iverilog.rs`
//! runs the same text through a real parser when one is installed.
//!
//! # The four properties
//!
//! Beyond the text, four things are asserted on their own because they are the
//! claims the crate makes rather than the output it happens to produce: byte
//! stability, structural stability across arenas, section order, and the
//! refusals.

#![allow(clippy::unwrap_used, clippy::expect_used)]

use ferrite_lithic::Design;
use ferrite_lithic_bits::Bits;
use ferrite_lithic_ir::{Circuit, NodeId};
use ferrite_lithic_rtl::{Error, Module, emit_library};

/// The accumulator from the front end's own docs: eight bits of state that add `d`
/// on every edge.
fn accumulator() -> (Design, ferrite_lithic::Signal) {
    let d = Design::new();
    let clk = d.input("clk", 1).unwrap();
    let data = d.input("d", 8).unwrap();
    let acc = d.wire(8).unwrap();
    let next = d.add(&acc, &data).unwrap();
    let next = d
        .reg(&next, &clk, &d.constant(false), &d.constant(false))
        .unwrap();
    d.drive(&acc, &next).unwrap();
    d.output("acc", 8, &acc).unwrap();
    (d, clk)
}

/// A module with a clock, built from a design's declared ports.
fn module(d: &Design, clock: &ferrite_lithic::Signal, name: &str) -> Module {
    Module::new(
        name,
        d.build().unwrap(),
        clock.id(),
        d.input_ports().iter().map(|s| s.id()).collect(),
        d.output_ports().iter().map(|s| s.id()).collect(),
    )
}

/// The smallest module with state in it.
#[test]
fn an_accumulator_emits_the_expected_module() {
    let (d, clk) = accumulator();
    let text = module(&d, &clk, "accumulator").emit().unwrap();
    let expected = r#"// Generated by ferrite-lithic-rtl. Do not edit; regenerate from the design.
// module `accumulator`
module accumulator (
  input  wire [0:0] clk,
  input  wire [7:0] d,
  output wire [7:0] acc
);
  wire [7:0] signal_Wire;
  wire [7:0] signal_Add;
  reg [7:0] signal_Reg;

  assign signal_Add = signal_Wire + d;
  always @(posedge clk) begin
    signal_Reg <= signal_Add;
  end

  assign signal_Wire = signal_Reg;

  assign acc = signal_Wire;

endmodule
"#;
    assert_eq!(text, expected);
}

/// A register with both control inputs tied low emits the shortest honest form: no
