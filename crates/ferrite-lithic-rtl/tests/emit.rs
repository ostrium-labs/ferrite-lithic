/// A literal has no edge, so there is no text that means "clocked by one".
#[test]
fn a_literal_clock_is_refused() {
    let mut circuit = Circuit::new();
    let data = circuit.wire(8).unwrap();
    circuit.set_name(data, "data").unwrap();
    let low = circuit.constant(Bits::constant(0, 1).unwrap());
    let reg = circuit
        .reg(data, low, low, low)
        .expect("the graph itself is legal: a literal clock is a description problem");
    let out = circuit.wire(8).unwrap();
    circuit.set_name(out, "out").unwrap();
    circuit.drive(out, reg).unwrap();
    let err = Module::new("lit", circuit, low, vec![data], vec![out])
        .emit()
        .unwrap_err();
    assert!(matches!(err, Error::ConstantClock { .. }), "{err:?}");
}

/// A second clock domain is refused rather than folded into the first, which is the
/// same boundary the simulator reports as `MultipleClocks`.
#[test]
fn a_second_clock_domain_is_refused() {
    let mut circuit = Circuit::new();
    let data = circuit.wire(8).unwrap();
    let first = circuit.wire(1).unwrap();
    let second = circuit.wire(1).unwrap();
    for (id, name) in [(data, "data"), (first, "clk"), (second, "clk2")] {
        circuit.set_name(id, name).unwrap();
    }
    let low = circuit.constant(Bits::constant(0, 1).unwrap());
    let reg = circuit.reg(data, second, low, low).unwrap();
    let out = circuit.wire(8).unwrap();
    circuit.set_name(out, "out").unwrap();
    circuit.drive(out, reg).unwrap();
    let err = Module::new("two", circuit, first, vec![data, first, second], vec![out])
        .emit()
        .unwrap_err();
    match err {
        Error::ClockMismatch {
            found, expected, ..
        } => {
            assert_eq!(found, second);
            assert_eq!(expected, first);
        }
        other => panic!("{other:?}"),
    }
}

