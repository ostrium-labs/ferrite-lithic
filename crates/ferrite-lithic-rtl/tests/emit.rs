/// `clear` holds; `reset` clears to zero. Both are asserted separately because both
/// are divergences from the reference's text, and neither is visible in a glance at
/// a golden.
#[test]
fn a_cleared_register_holds_and_a_reset_one_clears() {
    let d = Design::new();
    let clk = d.input("clk", 1).unwrap();
    let reset = d.input("reset", 1).unwrap();
    let hold = d.input("hold", 1).unwrap();
    let data = d.input("data", 8).unwrap();
    let reg = d.reg(&data, &clk, &reset, &hold).unwrap();
    d.output("q", 8, &reg).unwrap();
    let text = module(&d, &clk, "held").emit().unwrap();
    assert!(
        text.contains("if (reset == 1'b1) signal_Reg <= 8'h00;"),
        "{text}"
    );
    // `q <= q`, not `q <= 8'h00`: our `clear` gates the update, and a zero here
    // would disagree with the simulator.
    assert!(
        text.contains("else if (hold) signal_Reg <= signal_Reg;"),
        "{text}"
    );
    assert!(text.contains("else signal_Reg <= data;"), "{text}");
}

/// Memories, read ports, and a `case` node — the three shapes that need a block of
/// their own rather than an `assign`.
#[test]
fn memories_and_cases_emit_the_expected_module() {
    let d = Design::new();
    let clk = d.input("clk", 1).unwrap();
    let rst = d.input("rst", 1).unwrap();
    let we = d.input("we", 1).unwrap();
    let addr = d.input("addr", 4).unwrap();
    let data = d.input("data", 8).unwrap();
    let mem = d.mem(8, 16).unwrap();
    d.write_port(&mem, &data, &addr, &we).unwrap();
    let read = d.read_port(&mem, &addr, &we).unwrap();
    let held = d.reg(&read, &clk, &rst, &d.constant(false)).unwrap();
    let kind = d.slice(&data, 0, 2).unwrap();
    let wide = d.zero_extend(&kind, 8).unwrap();
    let picked = d
        .case_(&kind, &[(0, held.clone()), (1, wide.clone())], &data)
        .unwrap();
    d.output("q", 8, &picked).unwrap();
    let text = module(&d, &clk, "memory_and_case").emit().unwrap();
    let expected = r#"// Generated by ferrite-lithic-rtl. Do not edit; regenerate from the design.
// module `memory_and_case`
module memory_and_case (
  input  wire [0:0] clk,
  input  wire [0:0] rst,
  input  wire [0:0] we,
  input  wire [3:0] addr,
  input  wire [7:0] data,
  output wire [7:0] q
);
  reg [7:0] signal_Mem [0:15];
  wire [7:0] signal_ReadPort;
  reg [7:0] signal_Reg;
  wire [1:0] signal_Select;
  wire [1:0] signal_Select_1;
  wire [7:0] signal_Cat;
  reg [7:0] signal_Case;

  always @(posedge clk) begin
    if (we) signal_Mem[addr] <= data;
  end
  assign signal_ReadPort = we ? signal_Mem[addr] : '0;
  always @(posedge clk) begin
    if (rst == 1'b1) signal_Reg <= 8'h00;
    else signal_Reg <= signal_ReadPort;
  end
  assign signal_Select = data[0 +: 2];
  assign signal_Select_1 = signal_Select[0 +: 2];
  assign signal_Cat = {6'h00, signal_Select_1};
  always @* begin
    case (signal_Select)
      2'h0: signal_Case = signal_Reg;
      2'h1: signal_Case = signal_Cat;
      default: signal_Case = data;
    endcase
  end

  assign q = signal_Case;

endmodule
"#;
    assert_eq!(text, expected);
}

/// Every combinational node kind, in one module, so no kind can be added or changed
/// without this golden moving.
#[test]
fn every_operation_has_a_spelling() {
    let d = Design::new();
    let clk = d.input("clk", 1).unwrap();
    let rst = d.input("input", 1).unwrap();
    let a = d.input("a", 8).unwrap();
    let b = d.input("b", 8).unwrap();
    let addr = d.input("addr", 4).unwrap();
    let we = d.input("we", 1).unwrap();

    let sum = d.add(&a, &b).unwrap();
    let product = d.mul(&a, &b).unwrap();
    let quotient = d.udiv(&a, &b).unwrap();
    let squotient = d.sdiv(&a, &b).unwrap();
    let srem = d.srem(&a, &b).unwrap();
    let urem = d.urem(&a, &b).unwrap();
    let cmp = d.slt(&a, &b).unwrap();
    let ucmp = d.uge(&a, &b).unwrap();
    let eq = d.eq(&a, &b).unwrap();
    let inv = d.not(&a);
    let low = d.slice(&sum, 0, 4).unwrap();
    let pair_wide = d.concat(&[low, product.clone()]).unwrap();
    let pair = d.truncate(&pair_wide, 8).unwrap();
    let rep = d.replicate(&d.ones(1).unwrap(), 4).unwrap();
    let rep8 = d.zero_extend(&rep, 8).unwrap();
    let both = d.and(&cmp, &ucmp).unwrap();
    let both8 = d.zero_extend(&both, 8).unwrap();
    let sel = d.ite(&eq, &quotient, &squotient).unwrap();
    let mixed = d.or(&sel, &both8).unwrap();
    let wide = d.xor(&mixed, &pair).unwrap();
    let combined = d.or(&wide, &rep8).unwrap();
    let chosen = d
        .case_(&cmp, &[(0, srem.clone()), (1, urem.clone())], &inv)
        .unwrap();
    let total = d.add(&combined, &chosen).unwrap();
    let diff = d.sub(&total, &a).unwrap();

    let mem = d.mem(8, 16).unwrap();
    d.write_port(&mem, &a, &addr, &we).unwrap();
    let read = d.read_port(&mem, &addr, &d.constant(true)).unwrap();
    let held = d.reg(&diff, &clk, &rst, &d.constant(false)).unwrap();
    let from_mem = d.add(&held, &read).unwrap();
    d.output("q", 8, &from_mem).unwrap();
    let depth = Bits::constant(16, 32).unwrap();
    let sub = d
        .instance("fifo", &[("DEPTH", depth)], &[a.clone(), b.clone()], 8)
        .unwrap();
    d.output("last", 8, &sub).unwrap();

    let text = module(&d, &clk, "every_op").emit().unwrap();
    for expected in [
        "assign signal_Add = a + b;",
        "assign signal_Mul = a * b;",
        "assign signal_UDiv = a / b;",
        "assign signal_SDiv = $signed(a) / $signed(b);",
        "assign signal_SRem = $signed(a) % $signed(b);",
        "assign signal_URem = a % b;",
        "assign signal_Slt = $signed(a) < $signed(b);",
        "assign signal_Uge = a >= b;",
        "assign signal_Eq = a == b;",
        "assign signal_Not = ~a;",
        "assign signal_Select = signal_Add[0 +: 4];",
        "assign signal_Replicate = {4{1'h1}};",
        "assign signal_BitAnd = signal_Slt & signal_Uge;",
        "assign signal_Ite = signal_Eq ? signal_UDiv : signal_SDiv;",
        "assign signal_BitOr = signal_Ite | signal_Cat_2;",
        "assign signal_BitXor = signal_BitOr ^ signal_Select_1;",
        "assign signal_BitOr_1 = signal_BitXor | signal_Cat_1;",
        "assign signal_Sub = signal_Add_1 - a;",
        "reg [7:0] signal_Case;",
        "always @(posedge clk) begin",
        "if (we) signal_Mem[addr] <= a;",
        "assign signal_ReadPort = 1'h1 ? signal_Mem[addr] : '0;",
        "fifo #(.DEPTH(32'h00000010)) u_Instance (",
        ".i0 (a),",
        ".i1 (b),",
        ".o0 (signal_Instance)",
    ] {
        assert!(text.contains(expected), "missing {expected:?} in\n{text}");
    }
    // The reserved word in the port list, escaped.
    assert!(text.contains("input  wire [0:0] input_,"), "{text}");
}

