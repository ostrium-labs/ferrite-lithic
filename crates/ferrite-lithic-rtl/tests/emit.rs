/// An output with no driver is refused, rather than emitted as a floating net that
/// a lint would catch much later.
#[test]
fn an_undriven_output_port_is_refused() {
    let mut circuit = Circuit::new();
    let a = circuit.wire(8).unwrap();
    let out = circuit.wire(8).unwrap();
    circuit.set_name(a, "a").unwrap();
    circuit.set_name(out, "out").unwrap();
    // `check_with_inputs` passes: an undriven wire is a port if it is listed as one,
    // and this output port is not listed as an input.
    let err = Module::combinational("floating", circuit, vec![a], vec![out])
        .emit()
        .unwrap_err();
    assert!(matches!(err, Error::UndrivenPort { .. }), "{err:?}");
}

/// Two instances of one submodule produce one module definition.
#[test]
fn a_library_collapses_same_named_modules() {
    let (d, clk) = accumulator();
    let first = module(&d, &clk, "accumulator");
    let (other, other_clk) = accumulator();
    let second = module(&other, &other_clk, "accumulator");
    let text = emit_library(&[&first, &second]).unwrap();
    assert_eq!(text.matches("module accumulator (").count(), 1, "{text}");
    assert_eq!(text.matches("endmodule").count(), 1, "{text}");
}

/// Two modules with one name and different ports cannot both be defined.
#[test]
fn a_library_refuses_two_modules_that_disagree_about_their_ports() {
    let (d, clk) = accumulator();
    let first = module(&d, &clk, "thing");
    let mut circuit = Circuit::new();
    let a = circuit.wire(1).unwrap();
    let out = circuit.wire(1).unwrap();
    circuit.set_name(a, "a").unwrap();
    circuit.set_name(out, "out").unwrap();
    circuit.drive(out, a).unwrap();
    let second = Module::combinational("thing", circuit, vec![a], vec![out]);
    let err = emit_library(&[&first, &second]).unwrap_err();
    assert!(
        matches!(err, Error::ModuleSignatureConflict { ref name, .. } if name == "thing"),
        "{err:?}"
    );
}

/// A module's signature is its port counts, widths and naming scheme.
#[test]
fn a_signature_is_the_port_shape() {
    let (d, clk) = accumulator();
    let m = module(&d, &clk, "accumulator");
    let signature = m.signature().unwrap();
    assert_eq!(signature.inputs, 2);
    assert_eq!(signature.outputs, 1);
    assert_eq!(signature.input_widths, vec![1, 8]);
    assert_eq!(signature.output_widths, vec![8]);
}
