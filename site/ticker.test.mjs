import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import ts from "typescript";
let nextId = 0;
const frames = new Map();
globalThis.requestAnimationFrame = callback => { frames.set(++nextId, callback); return nextId; };
globalThis.cancelAnimationFrame = id => frames.delete(id);
let disconnected = false;
globalThis.IntersectionObserver = class { observe() {} disconnect() { disconnected = true; } };
const source = ts.transpileModule(readFileSync(new URL("./app/lib/ticker.ts", import.meta.url), "utf8"), { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const ticker = await import(`data:text/javascript;base64,${Buffer.from(source).toString("base64")}`);
const owner = {};
const elapsed = [];
ticker.onFrame(owner, value => elapsed.push(value));
assert.equal(frames.size, 0, "paused registrations must not schedule frames");
const step = now => { const [id, callback] = frames.entries().next().value; frames.delete(id); callback(now); };
ticker.resume(owner); step(100); step(116);
assert.deepEqual(elapsed, [0, 16]);
ticker.pause(owner); assert.equal(frames.size, 0, "last paused owner stops RAF");
ticker.resume(owner); step(5000); step(5016);
assert.deepEqual(elapsed, [0, 16, 16, 32], "offscreen time must not advance animation");
ticker.offFrame(owner); assert.equal(frames.size, 0);
ticker.resume(owner); assert.equal(frames.size, 0, "removed owners cannot restart");
const once = {};
ticker.onFrame(once, () => ticker.pause(once)); ticker.resume(once); step(6000);
assert.equal(frames.size, 0, "pausing inside draw must not schedule an idle frame");
ticker.offFrame(once);
ticker.onVisibility({}, () => {}, () => {})(); assert.equal(disconnected, true);
console.log("Ticker lifecycle checks passed");
